-- NIGHTOS migration 012 — visits.sales_amount
-- ───────────────────────────────────────────────────────────────
-- 来店ごとのお会計金額（円）を記録するカラムを追加。
-- 店舗スタッフが来店登録時に入力し、キャストの成績画面
-- （今月/年間の売上・再来店率トレンド）の実集計の元になる。
--
-- これまで成績画面は nightos_casts.monthly_sales / repeat_rate の
-- 静的列を直読みしており、登録した来店と連動していなかった。
-- 本カラム追加により visits からの実集計に切り替える。
--
-- 性質:
--   - default 0: 既存行・会計未確定の来店も 0 として扱える
--   - 後付け運用可能: 金額は来店登録時 or 後追いで入力
-- ═══════════════════════════════════════════════════════════════

alter table visits add column if not exists sales_amount bigint default 0;
